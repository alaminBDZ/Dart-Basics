void main() {
  // String
  String name = "Alamin";

  // Integer
  int age = 20;

  // Double
  double cgpa = 3.50;

  // Boolean
  bool isStudent = true;

  // Print variables
  print("Name: $name");
  print("Age: $age");
  print("CGPA: $cgpa");
  print("Student: $isStudent")

  // String interpolation
  print("$name is $age years old")

}
