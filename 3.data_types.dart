void main() {
  // String
  String name = "Alamin";

  // Integer
  int age = 20;

  // Double
  double height = 5.8;

  // Boolean
  bool isStudent = true;

  // List
  List<String> skills = ["Dart", "C++", "SQL"];

  // Set
  Set<String> languages = {"Bangla", "English", "Bangla"};

  // Map
  Map<String, dynamic> student = {"name": "Alamin", "age": 20, "cgpa": 3.50};

  print("Name: $name");
  print("Age: $age");
  print("Height: $height");
  print("Student: $isStudent");

  print("Skills: $skills");
  print("Languages: $languages");
  print("Student Information: $student");
}
