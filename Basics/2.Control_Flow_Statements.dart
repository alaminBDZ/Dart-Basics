void main() {
  int score = 85;

  // If-Else Statements
  if (score >= 90) {
    print("Grade: A");
  } else if (score >= 75) {
    print("Grade: B");
  } else {
    print("Grade: C");
  }

  // For Loop
  for (int i = 0; i < 3; i++) {
    print("Iteration: $i");
  }

  // While Loop
  int countdown = 2;
  while (countdown > 0) {
    print(countdown);
    countdown--;
  }
}
